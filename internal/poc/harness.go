// Package poc is M3: it realises a Counterexample as a real Go test, runs it
// with the Go toolchain and judges whether the model's violation reproduces.
// It is the only source of trust in the pipeline: every reported bug carries
// a verdict from here.
package poc

import (
	"encoding/json"
	"fmt"
	"go/token"
	"path"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"github.com/andreasfoo/go2lean/internal/contract"
)

// harnessData feeds the test template.
type harnessData struct {
	Package  string
	Imports  []string // extra import paths for named parameter/result types
	ID       string
	Decls    []string // parameter declarations
	Args     string   // comma-separated parameter names
	Func     string
	Rets     []string // result variable names (ret, or ret0, ret1, ...); empty when none
	RetTypes []string
	Pre      string // Go expression or ""
	SpecCall string // e.g. SpecSum(xs, ret) or ""
}

func (d harnessData) RetList() string { return strings.Join(d.Rets, ", ") }

var harnessTmpl = template.Must(template.New("poc").Parse(`package {{.Package}}

// Generated by go2lean for counterexample {{.ID}}. Do not edit.
// The test never fails on its own: it prints a GO2LEAN_RESULT line that
// the poc module turns into a verdict.

import (
	"encoding/json"
	"fmt"
	"testing"
{{- range .Imports}}
	"{{.}}"
{{- end}}
)

func TestGo2LeanPoC_{{.ID}}(go2leanT *testing.T) {
	_ = go2leanT
{{- range .Decls}}
	{{.}}
{{- end}}
{{- range $i, $r := .Rets}}
	var {{$r}} {{index $.RetTypes $i}}
{{- end}}
	go2leanRes := map[string]any{"panicked": false}
	func() {
		defer func() {
			if go2leanR := recover(); go2leanR != nil {
				go2leanRes["panicked"] = true
				go2leanRes["panic"] = fmt.Sprint(go2leanR)
			}
		}()
{{- if .Rets}}
		{{.RetList}} = {{.Func}}({{.Args}})
		go2leanRes["ret"] = fmt.Sprint({{.RetList}})
{{- else}}
		{{.Func}}({{.Args}})
{{- end}}
	}()
{{- if .Pre}}
	go2leanRes["pre"] = {{.Pre}}
{{- end}}
{{- if .SpecCall}}
	if !go2leanRes["panicked"].(bool) {
		go2leanRes["spec"] = {{.SpecCall}}
	}
{{- end}}
	go2leanB, _ := json.Marshal(go2leanRes)
	fmt.Println("GO2LEAN_RESULT " + string(go2leanB))
}
`))

// Harness renders the Go test for a counterexample.
func Harness(pkgName string, t *contract.Target, p *contract.Property, cx *contract.Counterexample, abi *contract.ABI) (string, error) {
	d := harnessData{Package: pkgName, ID: cx.ID, Func: t.Func}
	imports := map[string]bool{}
	for i, r := range abi.Results {
		name := "ret"
		if len(abi.Results) > 1 {
			name = fmt.Sprintf("ret%d", i)
		}
		if r.GoType == "" {
			return "", fmt.Errorf("result %d has no Go type", i)
		}
		d.Rets = append(d.Rets, name)
		d.RetTypes = append(d.RetTypes, r.GoType)
		if r.TypePkg != "" {
			imports[r.TypePkg] = true
		}
	}
	for _, ty := range abi.Types {
		for _, f := range ty.Fields {
			collectImports(f, imports)
		}
	}
	var names []string
	for _, prm := range abi.Params {
		decl, err := paramDecl(abi, prm, cx)
		if err != nil {
			return "", err
		}
		d.Decls = append(d.Decls, decl)
		names = append(names, prm.Go)
		collectImports(prm, imports)
		if prm.Kind == contract.ABIError && cx.Inputs[prm.Model[0]] != "nil" {
			imports["errors"] = true
		}
		if needsErrors(prm, cx.Objects[prm.Go]) {
			imports["errors"] = true
		}
	}
	// A nil pointer or an empty literal may leave a type package unused, and
	// an unused import does not compile: keep only the packages whose
	// qualifier the generated declarations mention.
	decls := strings.Join(d.Decls, "\n") + "\n" + strings.Join(d.RetTypes, " ")
	for ip := range imports {
		if strings.Contains(decls, path.Base(ip)+".") {
			d.Imports = append(d.Imports, ip)
		}
	}
	sort.Strings(d.Imports)
	d.Args = strings.Join(names, ", ")
	if abi.Method != "" && len(names) > 0 {
		// Methods: the receiver is the first parameter.
		d.Func = names[0] + "." + abi.Method
		d.Args = strings.Join(names[1:], ", ")
	}
	if p.Precondition != nil {
		d.Pre = p.Precondition.Go
	}
	if p.Spec != nil {
		specArgs := append(append([]string{}, names...), d.Rets...)
		d.SpecCall = fmt.Sprintf("%s(%s)", p.Spec.GoFunc, strings.Join(specArgs, ", "))
	}
	var b strings.Builder
	if err := harnessTmpl.Execute(&b, d); err != nil {
		return "", err
	}
	return b.String(), nil
}

// paramDecl builds `name := <literal>` for one parameter from the
// counterexample's inputs and memory.
func paramDecl(abi *contract.ABI, p contract.ABIParam, cx *contract.Counterexample) (string, error) {
	switch p.Kind {
	case contract.ABIInt:
		v, ok := cx.Inputs[p.Model[0]]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		return fmt.Sprintf("%s := %s(%s)", p.Go, p.GoType, v), nil
	case contract.ABIBool:
		v, ok := cx.Inputs[p.Model[0]]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		return fmt.Sprintf("%s := %s", p.Go, v), nil
	case contract.ABIError:
		if cx.Inputs[p.Model[0]] == "nil" {
			return fmt.Sprintf("var %s error", p.Go), nil
		}
		return fmt.Sprintf("%s := errors.New(\"go2lean: opaque error\")", p.Go), nil
	case contract.ABIString:
		raw, ok := cx.Objects[p.Go]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		var sv string
		if err := json.Unmarshal(raw, &sv); err != nil {
			return "", fmt.Errorf("string %s: %w", p.Go, err)
		}
		return fmt.Sprintf("%s := %s(%q)", p.Go, p.GoType, sv), nil
	case contract.ABIStruct, contract.ABIPtr:
		raw, ok := cx.Objects[p.Go]
		if !ok {
			return "", fmt.Errorf("counterexample has no object for %s", p.Go)
		}
		var v any
		if err := json.Unmarshal(raw, &v); err != nil {
			return "", fmt.Errorf("object %s: %w", p.Go, err)
		}
		if p.Kind == contract.ABIPtr && v == nil {
			return fmt.Sprintf("var %s %s", p.Go, p.GoType), nil
		}
		expr, err := literal(abi, p, v)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s := %s", p.Go, expr), nil
	case contract.ABISlice:
		n, err := strconv.Atoi(cx.Inputs[p.Go+"_len"])
		if err != nil {
			return "", fmt.Errorf("counterexample has no length for %s", p.Go)
		}
		c, err := strconv.Atoi(cx.Inputs[p.Go+"_cap"])
		if err != nil || c < n {
			c = n
		}
		elems := make([]string, n)
		mem := cx.Memory[p.Go]
		for i := range elems {
			elems[i] = "0"
			if i < len(mem) {
				elems[i] = mem[i]
			}
		}
		// go_hint "name[i]" havoc values (LLVM frontend) override memory.
		for _, h := range cx.Havoc {
			if h.GoHint == p.Go+"[i]" && h.Iter < n {
				elems[h.Iter] = h.Value
			}
		}
		if c == n {
			return fmt.Sprintf("%s := %s{%s}", p.Go, p.GoType, strings.Join(elems, ", ")), nil
		}
		return fmt.Sprintf("%s := append(make(%s, 0, %d), %s)", p.Go, p.GoType, c, strings.Join(elems, ", ")), nil
	}
	return "", fmt.Errorf("parameter %s: unsupported kind %s", p.Go, p.Kind)
}

// literal renders the Go expression for a value of the ABI type p: a struct
// is a JSON array of its fields in order, a pointer is null or its pointee.
func literal(abi *contract.ABI, p contract.ABIParam, v any) (string, error) {
	if p.TypeRef != "" {
		for _, t := range abi.Types {
			if t.GoType == p.TypeRef {
				p.Fields = t.Fields
			}
		}
	}
	switch p.Kind {
	case contract.ABIInt:
		s, ok := v.(string)
		if !ok {
			return "", fmt.Errorf("%s: expected an integer string, got %v", p.Go, v)
		}
		return fmt.Sprintf("%s(%s)", p.GoType, s), nil
	case contract.ABIBool:
		return fmt.Sprint(v), nil
	case contract.ABIString:
		sv, _ := v.(string)
		return fmt.Sprintf("%s(%q)", p.GoType, sv), nil
	case contract.ABIError:
		if v == "nil" || v == nil {
			return "error(nil)", nil
		}
		return "errors.New(\"go2lean: opaque error\")", nil
	case contract.ABIStruct:
		fields, ok := v.([]any)
		if !ok || len(fields) != len(p.Fields) {
			return "", fmt.Errorf("%s: expected %d fields, got %v", p.Go, len(p.Fields), v)
		}
		if strings.Contains(p.TypePkg, "/internal/") || strings.HasPrefix(p.TypePkg, "internal/") {
			return "", fmt.Errorf("%s: type %s lives in an internal package the test cannot import", p.Go, p.GoType)
		}
		var parts []string
		for i, f := range p.Fields {
			if p.TypePkg != "" && !token.IsExported(f.Go) {
				return "", fmt.Errorf("%s: cannot set unexported field %s of %s from the test", p.Go, f.Go, p.GoType)
			}
			e, err := literal(abi, f, fields[i])
			if err != nil {
				return "", err
			}
			parts = append(parts, f.Go+": "+e)
		}
		return p.GoType + "{" + strings.Join(parts, ", ") + "}", nil
	case contract.ABIPtr:
		if v == nil {
			return "(" + p.GoType + ")(nil)", nil
		}
		inner, err := literal(abi, *p.Pointee, v)
		if err != nil {
			return "", err
		}
		if p.Pointee.Kind == contract.ABIStruct {
			return "&" + inner, nil
		}
		// A pointer to a scalar: allocate it in a closure.
		return fmt.Sprintf("func() %s { v := %s; return &v }()", p.GoType, inner), nil
	}
	return "", fmt.Errorf("%s: cannot render kind %s", p.Go, p.Kind)
}

func collectImports(p contract.ABIParam, into map[string]bool) {
	for _, ip := range []string{p.TypePkg, p.ElemPkg} {
		if ip != "" {
			into[ip] = true
		}
	}
	for _, f := range p.Fields {
		collectImports(f, into)
	}
	if p.Pointee != nil {
		collectImports(*p.Pointee, into)
	}
}

// needsErrors reports whether rendering the object needs the errors package
// (a non-nil error somewhere inside a struct or pointee).
func needsErrors(p contract.ABIParam, raw json.RawMessage) bool {
	if raw == nil {
		return false
	}
	var v any
	if json.Unmarshal(raw, &v) != nil {
		return false
	}
	var walk func(p contract.ABIParam, v any) bool
	walk = func(p contract.ABIParam, v any) bool {
		switch p.Kind {
		case contract.ABIError:
			return v != nil && v != "nil"
		case contract.ABIStruct:
			fields, _ := v.([]any)
			for i, f := range p.Fields {
				if i < len(fields) && walk(f, fields[i]) {
					return true
				}
			}
		case contract.ABIPtr:
			return v != nil && p.Pointee != nil && walk(*p.Pointee, v)
		}
		return false
	}
	return walk(p, v)
}
