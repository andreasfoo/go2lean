#!/usr/bin/env python3
"""Regenerates testdata/goosesem/zz_seq_test.go (each func testX() bool as a
go2lean sequence spec) and zz_goose_test.go (each run in Go)."""
import glob
import re

D = "testdata/goosesem"
names = []
for f in sorted(glob.glob(D + "/*.go")):
    if not f.endswith("_test.go"):
        names += re.findall(r"^func (test\w+)\(\) bool", open(f).read(), re.M)
names = sorted(set(names))
hdr = "// Code generated by scripts/sem-gen.py; DO NOT EDIT.\n\npackage semantics\n"
spec = hdr + "\n// Each test of the suite as a go2lean sequence spec: the model must find\n// it true, as Go does (zz_goose_test.go).\n"
for n in names:
    spec += f"\n// go2lean:sequence {n}\nfunc Seq{n[0].upper() + n[1:]}() bool {{ return {n}() }}\n"
open(D + "/zz_seq_test.go", "w").write(spec)
test = hdr + '\nimport "testing"\n\n// TestGoose runs every test of the suite in Go: each must return true.\nfunc TestGoose(t *testing.T) {\n\tfor name, f := range map[string]func() bool{\n'
test += "".join(f'\t\t"{n}": {" " * 0}{n},\n' for n in names)
test += '\t} {\n\t\tif !f() {\n\t\t\tt.Errorf("%s is false in Go", name)\n\t\t}\n\t}\n}\n'
open(D + "/zz_goose_test.go", "w").write(test)
print(len(names), "tests")
